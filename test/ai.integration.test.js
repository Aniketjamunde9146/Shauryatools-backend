async function withBackend(client, run, env = { GROQ_API_KEY: "test-key" }) {
  const app = express();
  app.use(express.json({ limit: "32kb" }));
  app.use("/api/ai", createAIRouter({ client, env, sleep: async () => {} }));
  const server = app.listen(0, "127.0.0.1");
  await once(server, "listening");

  try {
    const { port } = server.address();
    return await run(`http://127.0.0.1:${port}`);
  } finally {
    server.closeAllConnections();
    await new Promise((resolve) => server.close(resolve));
  }
}

function successfulGroqClient(content = "Generated by Groq") {
  return {
    async post(url, body, options) {
      assert.equal(url, "https://api.groq.com/openai/v1/chat/completions");
      assert.equal(options.headers.Authorization, "Bearer test-key");
      assert.equal(body.model, "openai/gpt-oss-120b");
      assert.equal(body.temperature, 1);
      assert.equal(body.max_completion_tokens, 4096);
      assert.equal(body.top_p, 1);
      assert.equal(body.reasoning_effort, "medium");
      assert.equal(body.stop, null);
      return { data: { choices: [{ message: { content } }] } };
    },
  };
}

for (const tool of AI_TOOLS) {
  test(`frontend client -> backend -> Groq mock: ${tool}`, async () => {
    let calls = 0;
    const client = {
      ...successfulGroqClient(`Generated ${tool}`),
      async post(...args) {
        calls += 1;
        return successfulGroqClient(`Generated ${tool}`).post(...args);
      },
    };

    await withBackend(client, async (apiUrl) => {
      const { generateAI } = createAIClient(apiUrl);
      const response = await generateAI(tool, `Requirements for ${tool}`);
      assert.equal(response.data.success, true);
      assert.equal(response.data.data, `Generated ${tool}`);
      assert.equal(response.data.provider, "groq");
      assert.equal(calls, 1);
    });
  });
}

test("rejects missing, malformed, and oversized requests before Groq", async () => {
  const client = successfulGroqClient();
  await withBackend(client, async (apiUrl) => {
    const missing = await fetch(`${apiUrl}/api/ai`, {
      method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ tool: "readme" }),
    });
    assert.equal(missing.status, 400);
    assert.equal((await missing.json()).success, false);

    const malformed = await fetch(`${apiUrl}/api/ai`, {
      method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ tool: "bad tool", input: "content" }),
    });
    assert.equal(malformed.status, 400);

    const oversized = await fetch(`${apiUrl}/api/ai`, {
      method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ tool: "readme", input: "x".repeat(12001) }),
    });
    assert.equal(oversized.status, 400);
  });
});

test("rejects malformed landing-page JSON before Groq", async () => {
  let calls = 0;
  const client = {
    async post() {
      calls += 1;
      return { data: { choices: [{ message: { content: "unused" } }] } };
    },
  };

  await withBackend(client, async (apiUrl) => {
    const response = await fetch(`${apiUrl}/api/ai/landing`, {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ input: "{" }),
    });
    assert.equal(response.status, 400);
    assert.match((await response.json()).error, /valid JSON/);
    assert.equal(calls, 0);
  });
});

test("reports missing Groq configuration without exposing provider details", async () => {
  await withBackend(successfulGroqClient(), async (apiUrl) => {
    const response = await fetch(`${apiUrl}/api/ai`, {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ tool: "readme", input: "project" }),
    });
    assert.equal(response.status, 503);
    const payload = await response.json();
    assert.match(payload.error, /try again after some time/);
    assert.equal(payload.error.includes("GROQ"), false);
  }, {});
});

test("retries Groq 429 responses and succeeds", async () => {
  let attempts = 0;
  const client = {
    async post() {
      attempts += 1;
      if (attempts < 3) {
        const error = new Error("rate limited");
        error.response = { status: 429, headers: {} };
        throw error;
      }
      return { data: { choices: [{ message: { content: "Recovered" } }] } };
    },
  };

  await withBackend(client, async (apiUrl) => {
    const response = await fetch(`${apiUrl}/api/ai`, {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ tool: "readme", input: "project" }),
    });
    assert.equal(response.status, 200);
    assert.equal((await response.json()).data, "Recovered");
    assert.equal(attempts, 3);
  });
});

test("returns a clear error after Groq rate limits are exhausted", async () => {
  let attempts = 0;
  const client = {
    async post() {
      attempts += 1;
      const error = new Error("upstream private details");
      error.response = { status: 429, headers: {} };
      throw error;
    },
  };

  await withBackend(client, async (apiUrl) => {
    const response = await fetch(`${apiUrl}/api/ai`, {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ tool: "readme", input: "project" }),
    });
    const payload = await response.json();
    assert.equal(response.status, 429);
    assert.match(payload.error, /try again after some time/);
    assert.equal(payload.error.includes("private details"), false);
    assert.equal(attempts, 3);
  });
});

test("streams landing-page output through the frontend client", async () => {
  const html = "<!DOCTYPE html><html><body>Generated</body></html>";
  const event = `data: ${JSON.stringify({ choices: [{ delta: { content: html } }] })}\n\n`;
  const client = {
    async post(url, body, options) {
      assert.equal(url, "https://api.groq.com/openai/v1/chat/completions");
      assert.equal(body.stream, true);
      assert.equal(options.responseType, "stream");
      return { data: Readable.from([event, "data: [DONE]\n\n"]) };
    },
  };

  await withBackend(client, async (apiUrl) => {
    const chunks = [];
    const { streamLandingPage } = createAIClient(apiUrl);
    const result = await streamLandingPage({ businessName: "Example" }, (chunk) => chunks.push(chunk));
    assert.equal(result, html);
    assert.deepEqual(chunks, [html]);
  });
});